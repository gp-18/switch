# Find the sum of all items in a dictionary.
# Example 1: Input: {'a': 100, 'b': 200, 'c': 300} -> Output: 600
# Example 2: Input: {'x': 15, 'y': 25} -> Output: 40

data = {'a': 100, 'b': 200, 'c': 300}

total_sum = sum(data.values())
print("Dictionary:", data)
print("Sum of all items:", total_sum)
