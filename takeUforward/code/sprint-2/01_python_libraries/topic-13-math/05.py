# Write a program that demonstrates log(), log2(), and log10() on appropriate positive inputs.

# Example 1:
# Input: x = 8
# Output: log2(8) = 3.0, log10(100) = 2.0, log(e) = 1.0

# Example 2:
# Input: x = 1
# Output: log(1) = 0.0, log2(1) = 0.0, log10(1) = 0.0

import math

print(f"log2(8) = {math.log2(8)}")
print(f"log10(100) = {math.log10(100)}")
print(f"log(e) = {math.log(math.e)}")
