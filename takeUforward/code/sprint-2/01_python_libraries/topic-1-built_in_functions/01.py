# Given a list of integers, return a new sorted list without modifying the original list.

# Example 1:
# Input: nums = [5, 2, 9, 1, 5, 6]
# Output: [1, 2, 5, 5, 6, 9]

# Example 2:
# Input: nums = [10, -1, 3]
# Output: [-1, 3, 10]

nums = [5, 2, 9, 1, 5, 6]
sorted_nums = sorted(nums)
print(sorted_nums)
