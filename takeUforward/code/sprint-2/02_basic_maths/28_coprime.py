#
# Example 1:
# Input: a = 8, b = 15
# Output: True  # gcd(8, 15) = 1
#
# Example 2:
# Input: a = 12, b = 18
# Output: False  # gcd(12, 18) = 6 != 1
#
# Example 3 (Edge Case - Coprime with 1):
# Input: a = 1, b = 25
