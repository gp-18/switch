# Print a sentence containing both single and double quotation marks without causing a syntax error.

# Example 1:
# Output: He said, "It's a beautiful day outside."

# Example 2:
# Output: She asked, "Didn't you read the author's note?"

# Solution:
# Using double quotes to enclose the string and single quotes inside
print("He said, \"It's a beautiful day outside.\"")
print("She asked, \"Didn't you read the author's note?\"")