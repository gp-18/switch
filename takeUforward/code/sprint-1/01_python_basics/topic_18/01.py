# State the time complexity of printing each item in a list once.

# Example 1:
# Scenario: Iterating through a list of n elements once: for item in lst: print(item)
# Output: Time Complexity: O(n) (Linear Time)

# Example 2:
# Explanation: As input size n doubles, the number of operations doubles proportionally.

lst = ["apple", "banana", "cherry"]
for item in lst:
    print(item)

print("\nTime Complexity: O(n) (Linear Time)")
print("Explanation: As input size n doubles, the number of operations doubles proportionally.")
