# Read two numbers and print their average.

# Example 1:
# Input: Enter first number: 10, Enter second number: 20
# Output: The average of 10.0 and 20.0 is: 15.0

# Example 2:
# Input: Enter first number: 5, Enter second number: 8
# Output: The average of 5.0 and 8.0 is: 6.5

num1 = float(input("Enter first number: "))
num2 = float(input("Enter second number: "))
average = (num1 + num2) / 2
print("The average of", num1, "and", num2, "is:", average)
