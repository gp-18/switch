# Use an f-string to print a person's name and age.

# Example 1:
# Input: name = "Alice", age = 22
# Output: "My name is Alice and I am 22 years old."

# Example 2:
# Input: name = "Bob", age = 35
# Output: "My name is Bob and I am 35 years old."


name = input("Enter your name: ")
age = input("Enter your age: ")
# Print the name and age using an f-string
print(f"My name is {name} and I am {age} years old.")