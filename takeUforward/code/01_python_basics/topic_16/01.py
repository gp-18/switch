# Find the minimum, maximum, and sum of a list using built-ins.

# Example 1:
# Input: [4, 1, 9, 2, 8]
# Output: Min: 1, Max: 9, Sum: 24

# Example 2:
# Input: [10, -5, 20]
# Output: Min: -5, Max: 20, Sum: 25

numbers = [4, 1, 9, 2, 8]
print(f"Min: {min(numbers)}, Max: {max(numbers)}, Sum: {sum(numbers)}")

numbers2 = [10, -5, 20]
print(f"Min: {min(numbers2)}, Max: {max(numbers2)}, Sum: {sum(numbers2)}")
